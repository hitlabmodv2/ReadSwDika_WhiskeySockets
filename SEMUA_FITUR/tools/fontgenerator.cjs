// ─── CONST ──────────────────────────────────────────────────────────────────
const PER_PAGE = 15;

// ─── HANDLER ────────────────────────────────────────────────────────────────
async function handleFontgen(m, hisoka, { getEmoji, logCommand }) {
  const prefix = m.prefix || '.';
  const args = m.text.trim().split(/\s+/);
  const pageArg = args[args.length - 1];
  let page = 1;
  let teks;

  if (/^\d+$/.test(pageArg)) {
    page = parseInt(pageArg);
    teks = args.slice(0, -1).join(' ');
  } else {
    teks = args.join(' ');
  }

  const emoji = getEmoji('tools') || '🔤';
  const totalPages = Math.ceil(FONTS.length / PER_PAGE);

  if (!teks) {
    const usage = [
      `📋 *Command:* ${prefix}font`,
      ``,
      `${emoji} *Font Generator*`,
      ``,
      `Ubah teksmu ke berbagai gaya font keren!`,
      ``,
      `*Cara pakai:*`,
      `• ${prefix}font <teks>`,
      `• ${prefix}font <teks> <halaman>`,
      ``,
      `*Contoh:*`,
      `• ${prefix}font Wily Bot`,
      `• ${prefix}font Wily Bot 2`,
      ``,
      `Total font: *${FONTS.length} gaya*`,
      `Per halaman: *${PER_PAGE} font*`,
      `Total halaman: *${totalPages}*`,
    ].join('\n');
    await hisoka.sendMessage(m.from, { text: usage }, { quoted: m });
    logCommand(m, hisoka, 'fontgen');
    return;
  }

  if (page < 1 || page > totalPages) {
    await hisoka.sendMessage(m.from, {
      text: `❌ Halaman tidak valid! Halaman tersedia: 1–${totalPages}`
    }, { quoted: m });
    return;
  }

  const start = (page - 1) * PER_PAGE;
  const slice = FONTS.slice(start, start + PER_PAGE);

  const lines = [
    `📋 *Command:* ${prefix}font`,
    ``,
    `${emoji} *Font Generator* — Halaman ${page}/${totalPages}`,
    `🔤 Teks: *${teks}*`,
    `━━━━━━━━━━━━━━━━━━`,
  ];

  for (let i = 0; i < slice.length; i++) {
    const f = slice[i];
    let result;
    try { result = f.fn(teks); } catch { result = teks; }
    lines.push(`*${start + i + 1}. ${f.name}*`);
    lines.push(result);
    lines.push('');
  }

  lines.push(`━━━━━━━━━━━━━━━━━━`);
  if (page < totalPages) {
    lines.push(`➡️ Halaman berikutnya: *${prefix}font ${teks} ${page + 1}*`);
  }
  if (page > 1) {
    lines.push(`⬅️ Halaman sebelumnya: *${prefix}font ${teks} ${page - 1}*`);
  }

  await hisoka.sendMessage(m.from, { text: lines.join('\n') }, { quoted: m });
  logCommand(m, hisoka, 'fontgen');
}

module.exports.handleFontgen = handleFontgen;
module.exports.FONTS = FONTS;
